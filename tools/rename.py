#!/usr/bin/env python3
"""Rename a symbol everywhere it's spelled in the tree.

  tools/rename.py TARGET OLD NEW [ADDRESS]

TARGET is langimg or sces. Updates config/<target>/symbol_addrs.txt (adds
a line for ADDRESS, or for OLD's address when OLD is a func_XXXXXXXX/
D_XXXXXXXX placeholder, if there isn't one), every word OLD in src/ and
include/ (INCLUDE_ASM lines included), and moves a function's .s file under
asm/<target>/nonmatchings/. The other asm that refers to the symbol is
regenerated by the next make (splat).
"""
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def main():
    if len(sys.argv) not in (4, 5):
        sys.exit(__doc__)
    target, old, new = sys.argv[1:4]
    addr = int(sys.argv[4], 16) if len(sys.argv) == 5 else None
    word = re.compile(rf"(?<![\w.$]){re.escape(old)}(?![\w.$])")

    syms = ROOT / "config" / target / "symbol_addrs.txt"
    s = syms.read_text()
    if re.search(rf"^{re.escape(old)} =", s, re.M):
        s = re.sub(rf"^{re.escape(old)} =", f"{new} =", s, flags=re.M)
    else:
        m = re.fullmatch(r"(?:func|D)_([0-9A-F]{8})", old)
        if addr is None and m:
            addr = int(m.group(1), 16)
        if addr is None:
            sys.exit(f"{old} isn't in {syms.name}: give its address")
        kind = "type:func" if old.startswith("func_") else ""
        line = f"{new} = 0x{addr:08X};" + (f" // {kind}" if kind else "") + "\n"
        # Before the generated PsyQ block, which is regenerated.
        i = s.find("// PsyQ library functions")
        s = (s[:i].rstrip("\n") + "\n" + line + "\n" + s[i:]) if i >= 0 else s.rstrip("\n") + "\n" + line
    syms.write_text(s)

    for d in ("src", "include"):
        for p in (ROOT / d).rglob("*"):
            if p.suffix in (".c", ".cpp", ".h") and p.is_file():
                t = p.read_text()
                if word.search(t):
                    p.write_text(word.sub(new, t))
                    print(f"updated {p.relative_to(ROOT)}")

    for p in (ROOT / "asm" / target / "nonmatchings").glob(f"*/{old}.s"):
        dest = p.with_name(f"{new}.s")
        subprocess.run(["git", "mv", str(p), str(dest)], cwd=ROOT, check=True)
        dest.write_text(word.sub(new, dest.read_text()))
        print(f"moved {p.relative_to(ROOT)} -> {dest.name}")


if __name__ == "__main__":
    main()
